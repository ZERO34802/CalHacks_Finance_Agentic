"""Store interface. Everything persistent goes through this.

SQLiteStore is the first implementation; SpacetimeDB slots in behind the
same Protocol later, so nobody else changes code.
"""
from __future__ import annotations

from typing import Optional, Protocol, TypeVar

from pydantic import BaseModel

from contracts import (Case, ContractTerm, Document, Employee, MemoryEntry, PaidInvoice, PO, Receipt, Scoreboard,
                       Step, Vendor)


T = TypeVar("T", bound=BaseModel)


class Store(Protocol):
    # cases
    def save_case(self, case: Case) -> None: ...
    def get_case(self, case_id: str) -> Optional[Case]: ...
    def list_cases(self, vendor_id: Optional[str] = None) -> list[Case]: ...

    # registry: atomic insert-or-get. Returns the case_id that owns fp (existing owner wins).
    def claim_fingerprint(self, fingerprint: str, case_id: str) -> str: ...
    def find_documents(self, sha256: str) -> list[tuple[str, Document]]: ...  # (case_id, doc), from saved cases

    # trace (append_step upserts by step.id: called on start and on finish)
    def append_step(self, step: Step) -> None: ...
    def list_steps(self, case_id: str, run_id: Optional[str] = None) -> list[Step]: ...

    # vendors
    def save_vendor(self, vendor: Vendor) -> None: ...
    def get_vendor(self, vendor_id: str) -> Optional[Vendor]: ...
    def list_vendors(self) -> list[Vendor]: ...

    # system of record (ERP world); read-only for agents
    def save_po(self, po: PO) -> None: ...
    def get_po(self, po_number: str) -> Optional[PO]: ...
    def save_receipt(self, receipt: Receipt) -> None: ...
    def list_receipts(self, po_number: str) -> list[Receipt]: ...
    def save_contract_term(self, term: ContractTerm) -> None: ...
    def list_contract_terms(self, vendor_id: str) -> list[ContractTerm]: ...
    def save_paid(self, paid: PaidInvoice) -> None: ...
    def list_paid(self, vendor_id: str) -> list[PaidInvoice]: ...
    def save_employee(self, emp: Employee) -> None: ...
    def list_employees(self) -> list[Employee]: ...

    # generic records for P1 workflow data (follow-ups, onboarding, skill proposals, controls...)
    # kind: short snake name; key: unique within kind; idx: secondary lookup (e.g. case_id or vendor_id)
    def put_record(self, kind: str, key: str, model: BaseModel, idx: str = "") -> None: ...
    def get_record(self, model: type[T], kind: str, key: str) -> Optional[T]: ...
    def list_records(self, model: type[T], kind: str, idx: Optional[str] = None) -> list[T]: ...

    # memory
    def save_memory(self, entry: MemoryEntry) -> None: ...
    def list_memory(self, subject: Optional[str] = None) -> list[MemoryEntry]: ...
    def delete_memory(self, entry_id: str) -> None: ...  # forget (Memory Writer); history stays in records

    # evals
    def save_scoreboard(self, board: Scoreboard) -> None: ...
    def latest_scoreboard(self) -> Optional[Scoreboard]: ...

    # maintenance: wipe run state (cases, steps, fingerprints, documents); world/vendors/memory are re-seeded
    def reset(self, keep_scoreboards: bool = True) -> None: ...
